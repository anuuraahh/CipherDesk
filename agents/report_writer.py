"""
Report Writer Agent
Synthesizes the News Analyst and Price Analyst outputs into one
structured, readable report for the end user.

"""
from langchain_core.messages import SystemMessage, HumanMessage
from config import get_llm

SYSTEM_PROMPT = """ You are the Report Writer agent, the final step in a crypto
analysis pipeline. You'll receive a price analysis and a news analysis for a
coin. 

Combine them into a single well-structured report with these sections:

# <Coin Name> Market Report

## Price Overview
## News & Sentiment
## Key Takeaways (3-4 bullet points)
## Disclaimer

The disclaimer must state this is not financial advice and is generated by
an AI system for informational/educational purposes only.

Keep it professional, concise, and readable — this is a portfolio project
report, not a wall of text.

"""

def write_report(coin: str, price_analysis: dict, news_analysis: dict) -> str:
    llm = get_llm(temperature=0.4)
    content = (
        f"Coin: {coin}\n\n"
        f"PRICE ANALYSIS:\n{price_analysis['summary']}\n\n"
        f"NEWS ANALYSIS:\n{news_analysis['summary']}\n"
    )
    messages = [
        SystemMessage(content=SYSTEM_PROMPT), 
        HumanMessage(content=content)
    ]
    
    response = llm.invoke(messages)
    return response.content.strip()